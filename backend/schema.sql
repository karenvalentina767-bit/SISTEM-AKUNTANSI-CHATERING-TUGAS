-- 4. INVOICE (tabel pembayaran)
-- ------------------------------------------------------------
create table if not exists public.pembayaran (
  id bigint generated by default as identity primary key,
  pesanan_id bigint not null references public.pesanan_event(id) on delete cascade,
  no_invoice text not null unique,
  tanggal_tagihan date not null,
  tanggal_tempo date not null,
  pajak_ppn numeric(14, 2) not null default 0,
  total_tagihan numeric(14, 2) not null check (total_tagihan >= 0),
  status_bayar text not null default 'Belum Bayar',
  created_at timestamptz not null default now()
);
alter table public.pembayaran add column if not exists jumlah_dibayar numeric(14, 2) not null default 0;
alter table public.pembayaran drop constraint if exists pembayaran_status_bayar_check;
update public.pembayaran set status_bayar = 'Belum Bayar' where status_bayar = 'Belum Lunas';
alter table public.pembayaran alter column status_bayar set default 'Belum Bayar';
alter table public.pembayaran add constraint pembayaran_status_bayar_check
  check (status_bayar in ('Belum Bayar', 'DP', 'Setengah', 'Lunas'));

-- Status dihitung otomatis dari jumlah yang sudah dibayar:
--   0            → Belum Bayar
--   < 50%        → DP
--   50% s/d <100%→ Setengah
--   100%         → Lunas
create or replace function public.hitung_status(dibayar numeric, total numeric)
returns text language sql immutable as $$
  select case
    when coalesce(dibayar, 0) <= 0 then 'Belum Bayar'
    when dibayar >= total then 'Lunas'
    when dibayar >= total / 2 then 'Setengah'
    else 'DP' end
$$;

create or replace function public.set_status_bayar()
returns trigger language plpgsql as $$
begin
  new.status_bayar := public.hitung_status(new.jumlah_dibayar, new.total_tagihan);
  return new;
end $$;
drop trigger if exists pembayaran_status_trg on public.pembayaran;
create trigger pembayaran_status_trg before insert or update on public.pembayaran
  for each row execute function public.set_status_bayar();

-- ------------------------------------------------------------
-- 5. RIWAYAT TRANSAKSI PEMBAYARAN (DP, cicilan, pelunasan)
-- ------------------------------------------------------------
create table if not exists public.transaksi_bayar (
  id bigint generated by default as identity primary key,
  pembayaran_id bigint not null references public.pembayaran(id) on delete cascade,
  tanggal date not null default current_date,
  jumlah numeric(14, 2) not null check (jumlah > 0),
  metode text not null default 'Transfer Bank',
  catatan text not null default '',
  dibuat_oleh uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists transaksi_pembayaran_idx on public.transaksi_bayar (pembayaran_id);
create index if not exists transaksi_tanggal_idx on public.transaksi_bayar (tanggal);

-- Tolak pembayaran yang melebihi sisa tagihan
create or replace function public.cek_lebih_bayar()
returns trigger language plpgsql as $$
declare v_total numeric; v_dibayar numeric;
begin
  select total_tagihan, jumlah_dibayar into v_total, v_dibayar
  from public.pembayaran where id = new.pembayaran_id;
  if v_dibayar + new.jumlah > v_total + 0.5 then
    raise exception 'Jumlah melebihi sisa tagihan (sisa Rp %).', round(v_total - v_dibayar);
  end if;
  return new;
end $$;
drop trigger if exists transaksi_cek_trg on public.transaksi_bayar;
create trigger transaksi_cek_trg before insert on public.transaksi_bayar
  for each row execute function public.cek_lebih_bayar();

-- Setiap transaksi masuk/dihapus → hitung ulang total dibayar invoice
create or replace function public.sinkron_dibayar()
returns trigger language plpgsql as $$
declare pid bigint;
begin
  if tg_op = 'DELETE' then pid := old.pembayaran_id; else pid := new.pembayaran_id; end if;
  update public.pembayaran
    set jumlah_dibayar = coalesce((select sum(jumlah) from public.transaksi_bayar where pembayaran_id = pid), 0)
    where id = pid;
  return null;
end $$;
drop trigger if exists transaksi_sinkron_trg on public.transaksi_bayar;
create trigger transaksi_sinkron_trg after insert or update or delete on public.transaksi_bayar
  for each row execute function public.sinkron_dibayar();

-- Migrasi: invoice "Lunas" dari versi lama dicatat sebagai satu transaksi pelunasan
insert into public.transaksi_bayar (pembayaran_id, tanggal, jumlah, metode, catatan, dibuat_oleh)
select p.id, p.tanggal_tagihan, p.total_tagihan, 'Transfer Bank', 'Migrasi data lama', null
from public.pembayaran p
where p.status_bayar = 'Lunas' and p.jumlah_dibayar = 0 and p.total_tagihan > 0
  and not exists (select 1 from public.transaksi_bayar t where t.pembayaran_id = p.id);

create index if not exists pembayaran_status_idx on public.pembayaran (status_bayar);
create index if not exists pembayaran_tempo_idx on public.pembayaran (tanggal_tempo);

