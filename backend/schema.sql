-- 2. PELANGGAN
-- ------------------------------------------------------------
create table if not exists public.pelanggan (
  id bigint generated by default as identity primary key,
  nama_pelanggan text not null,
  no_hp text not null,
  email text not null default '',
  created_at timestamptz not null default now()
);
-- Nomor HP yang dinormalisasi (62812...) untuk mengenali customer lama
alter table public.pelanggan add column if not exists no_hp_normal text;

create or replace function public.normalisasi_hp(hp text)
returns text language sql immutable as $$
  select case
    when d like '0%'  then '62' || substr(d, 2)
    when d like '8%'  then '62' || d
    else d end
  from (select regexp_replace(coalesce(hp, ''), '\D', '', 'g') as d) x
$$;

create or replace function public.set_hp_normal()
returns trigger language plpgsql as $$
begin
  new.no_hp_normal := public.normalisasi_hp(new.no_hp);
  return new;
end $$;
drop trigger if exists pelanggan_hp_trg on public.pelanggan;
create trigger pelanggan_hp_trg before insert or update of no_hp on public.pelanggan
  for each row execute function public.set_hp_normal();
update public.pelanggan set no_hp_normal = public.normalisasi_hp(no_hp) where no_hp_normal is null;
create index if not exists pelanggan_hp_idx on public.pelanggan (no_hp_normal);

