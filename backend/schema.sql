-- ------------------------------------------------------------
-- 7. BOOKING DALAM SATU TRANSAKSI
--    Mengenali customer lama dari nomor HP, membuat pesanan
--    dengan nomor urut, membuat invoice, dan mencatat DP (jika ada).
-- ------------------------------------------------------------
create or replace function public.buat_booking(
  p_nama text, p_hp text, p_email text,
  p_nama_event text, p_tanggal_event date, p_paket text,
  p_pax int, p_harga numeric, p_metode text,
  p_tgl_tagihan date, p_tgl_tempo date, p_dp numeric default 0
) returns json language plpgsql security invoker set search_path = public as $$
declare
  v_pelanggan bigint;
  v_baru boolean := false;
  v_pesanan record;
  v_invoice bigint;
  v_subtotal numeric := round(p_pax * p_harga, 2);
  v_ppn numeric := round(p_pax * p_harga * 0.11, 2);
  v_total numeric;
begin
  if public.peran_saya() not in ('owner', 'admin') then
    raise exception 'Akun viewer tidak boleh menambah data.';
  end if;
  v_total := v_subtotal + v_ppn;

  select id into v_pelanggan from public.pelanggan
  where no_hp_normal = public.normalisasi_hp(p_hp)
  order by created_at limit 1;

  if v_pelanggan is null then
    insert into public.pelanggan (nama_pelanggan, no_hp, email)
    values (p_nama, p_hp, coalesce(p_email, '')) returning id into v_pelanggan;
    v_baru := true;
  elsif coalesce(p_email, '') <> '' then
    update public.pelanggan set email = p_email where id = v_pelanggan and email = '';
  end if;

  insert into public.pesanan_event (pelanggan_id, nama_event, tanggal_event, jenis_paket,
    jumlah_pax, harga_per_pax, total_penjualan, metode_pembayaran)
  values (v_pelanggan, p_nama_event, p_tanggal_event, p_paket, p_pax, p_harga, v_subtotal, p_metode)
  returning id, no_pesanan into v_pesanan;

  insert into public.pembayaran (pesanan_id, no_invoice, tanggal_tagihan, tanggal_tempo, pajak_ppn, total_tagihan)
  values (v_pesanan.id, replace(v_pesanan.no_pesanan, 'ORD-', 'INV-'), p_tgl_tagihan, p_tgl_tempo, v_ppn, v_total)
  returning id into v_invoice;

  if coalesce(p_dp, 0) > 0 then
    insert into public.transaksi_bayar (pembayaran_id, tanggal, jumlah, metode, catatan)
    values (v_invoice, p_tgl_tagihan, p_dp, p_metode, 'Pembayaran awal saat booking');
  end if;

  return json_build_object(
    'no_pesanan', v_pesanan.no_pesanan,
    'no_invoice', replace(v_pesanan.no_pesanan, 'ORD-', 'INV-'),
    'pelanggan_baru', v_baru
  );
end $$;

-- ------------------------------------------------------------
-- 8. KEAMANAN (Row Level Security)
--    viewer : hanya melihat
--    admin  : melihat + menambah + mengubah
--    owner  : semua, termasuk MENGHAPUS dan mengatur peran pengguna
-- ------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.pelanggan enable row level security;
alter table public.pesanan_event enable row level security;
alter table public.pembayaran enable row level security;
alter table public.transaksi_bayar enable row level security;
alter table public.pengeluaran enable row level security;
alter table public.penomoran enable row level security; -- tanpa policy: hanya lewat fungsi

drop policy if exists profiles_baca on public.profiles;
create policy profiles_baca on public.profiles for select to authenticated
  using (id = auth.uid() or public.peran_saya() is not null);
drop policy if exists profiles_ubah on public.profiles;
create policy profiles_ubah on public.profiles for update to authenticated
  using (public.peran_saya() = 'owner') with check (public.peran_saya() = 'owner');

do $$
declare t text;
begin
  foreach t in array array['pelanggan', 'pesanan_event', 'pembayaran', 'transaksi_bayar', 'pengeluaran'] loop
    execute format('drop policy if exists %1$s_baca on public.%1$s', t);
    execute format('drop policy if exists %1$s_tambah on public.%1$s', t);
    execute format('drop policy if exists %1$s_ubah on public.%1$s', t);
    execute format('drop policy if exists %1$s_hapus on public.%1$s', t);
    execute format($p$create policy %1$s_baca on public.%1$s for select to authenticated
      using (public.peran_saya() in ('owner','admin','viewer'))$p$, t);
    execute format($p$create policy %1$s_tambah on public.%1$s for insert to authenticated
      with check (public.peran_saya() in ('owner','admin'))$p$, t);
    execute format($p$create policy %1$s_ubah on public.%1$s for update to authenticated
      using (public.peran_saya() in ('owner','admin')) with check (public.peran_saya() in ('owner','admin'))$p$, t);
    execute format($p$create policy %1$s_hapus on public.%1$s for delete to authenticated
      using (public.peran_saya() = 'owner')$p$, t);
  end loop;
end $$;

