-- ------------------------------------------------------------
-- 11. SIMULASI PAYMENT GATEWAY (untuk demo / tugas kuliah)
--     Pembeli klik "Bayar" → halaman bayar tiruan (QRIS / Virtual Account / E-Wallet)
--     → "Simulasikan pembayaran berhasil" → pembayaran LANGSUNG tercatat.
--     Owner tidak perlu verifikasi apa pun: pesanan otomatis diterima, invoice dibuat,
--     status bayar berubah otomatis (DP → Setengah → Lunas).
--     CATATAN: ini tiruan. Di dunia nyata, fungsi ini dipanggil oleh webhook
--     payment gateway (Midtrans/Xendit), bukan oleh browser pembeli.
-- ------------------------------------------------------------
create or replace function public.bayar_simulasi(
  p_kode text, p_hp text, p_jumlah numeric, p_metode text
) returns json language plpgsql security definer set search_path = public as $$
declare
  r public.pesanan_masuk;
  v_harga numeric;
  v_pembayaran bigint;
  v_total numeric;
  v_dibayar numeric;
  v_ref text := 'SIM-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8));
  v_status text;
begin
  r := public.cari_pesanan_pembeli(p_kode, p_hp);
  if r.status = 'Ditolak' then raise exception 'Pesanan ini tidak dapat dilayani, jadi tidak perlu dibayar.'; end if;
  if p_metode is null or p_metode not in ('Transfer Bank', 'QRIS', 'E-Wallet', 'Kartu Debit/Kredit') then
    raise exception 'Pilih metode pembayaran.'; end if;

  -- Pembayaran pertama paket katalog → pesanan otomatis diterima + invoice dibuat
  if r.pesanan_id is null then
    v_harga := (public.harga_paket(r.jenis_paket)).harga;
    if v_harga is null then raise exception 'Harga paket custom belum dikonfirmasi admin. Tunggu kabar dari kami dulu, ya.'; end if;
    perform public._booking_dari_online(r.id, v_harga);
    select pesanan_id into r.pesanan_id from public.pesanan_masuk where id = r.id;
  end if;

  select b.id, b.total_tagihan, b.jumlah_dibayar into v_pembayaran, v_total, v_dibayar
    from public.pembayaran b where b.pesanan_id = r.pesanan_id limit 1;
  if v_total - v_dibayar <= 0 then raise exception 'Tagihan ini sudah lunas.'; end if;
  if p_jumlah is null or p_jumlah <= 0 then raise exception 'Jumlah tidak valid.'; end if;
  -- Pembayaran pertama minimal DP 50% (samakan dengan dpMinimalPersen di pengaturan.js)
  if v_dibayar = 0 and p_jumlah < round(v_total * 0.5) - 0.5 then
    raise exception 'Pembayaran pertama minimal DP 50%% (Rp %).', replace(to_char(round(v_total * 0.5), 'FM999,999,999,990'), ',', '.');
  end if;
  -- (pembayaran melebihi sisa ditolak oleh trigger cek_lebih_bayar)

  insert into public.transaksi_bayar (pembayaran_id, tanggal, jumlah, metode, catatan)
  values (v_pembayaran, current_date, round(p_jumlah, 2), p_metode,
          'Simulasi payment gateway ' || v_ref || ' (' || r.kode || ')');

  select status_bayar into v_status from public.pembayaran where id = v_pembayaran;
  return json_build_object('ok', true, 'ref', v_ref, 'status_bayar', v_status);
end $$;
revoke execute on function public.bayar_simulasi(text, text, numeric, text) from public;
grant execute on function public.bayar_simulasi(text, text, numeric, text) to anon, authenticated;
