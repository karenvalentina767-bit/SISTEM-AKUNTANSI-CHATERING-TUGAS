-- ------------------------------------------------------------
-- 1. PENGGUNA & PERAN (owner / admin / viewer)
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  nama text not null default '',
  role text not null default 'viewer' check (role in ('owner', 'admin', 'viewer')),
  created_at timestamptz not null default now()
);

-- Pengguna pertama yang terdaftar otomatis menjadi owner,
-- pengguna berikutnya menjadi viewer sampai diubah owner.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, nama, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'nama', split_part(coalesce(new.email, ''), '@', 1)),
    case when exists (select 1 from public.profiles) then 'viewer' else 'owner' end
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Buat profil untuk user yang sudah ada sebelum skema ini dijalankan
insert into public.profiles (id, email, nama, role)
select u.id, coalesce(u.email, ''), split_part(coalesce(u.email, ''), '@', 1), 'viewer'
from auth.users u
on conflict (id) do nothing;
update public.profiles set role = 'owner'
where id = (select id from public.profiles order by created_at limit 1)
  and not exists (select 1 from public.profiles where role = 'owner');

-- Peran user yang sedang login (dipakai oleh semua policy RLS)
create or replace function public.peran_saya()
returns text language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid()
$$;

-- Owner tidak bisa mengubah perannya sendiri (mencegah sistem tanpa owner)
create or replace function public.jaga_peran()
returns trigger language plpgsql as $$
begin
  if new.role is distinct from old.role and new.id = auth.uid() then
    raise exception 'Tidak bisa mengubah peran akun sendiri.';
  end if;
  return new;
end $$;
drop trigger if exists jaga_peran_trg on public.profiles;
create trigger jaga_peran_trg before update on public.profiles
  for each row execute function public.jaga_peran();

