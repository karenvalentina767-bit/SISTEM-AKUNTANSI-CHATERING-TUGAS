-- 10. CEK TAGIHAN & LAPOR BAYAR (pembeli, tanpa login)
--     Pembeli membuka menu "Cek tagihan", mengetik KODE PESANAN + NOMOR HP.
--     Setiap pembeli hanya bisa melihat tagihannya sendiri (kode dan HP harus cocok).
--     Pembeli melapor "sudah bayar" → owner/admin memverifikasi →
--     pembayaran tercatat dan status invoice berubah otomatis.
-- ------------------------------------------------------------
create table if not exists public.laporan_bayar (
  id bigint generated by default as identity primary key,
  pesanan_masuk_id bigint not null references public.pesanan_masuk(id) on delete cascade,
  pembayaran_id bigint not null references public.pembayaran(id) on delete cascade,
  jumlah numeric(14, 2) not null check (jumlah > 0),
  metode text not null check (metode in ('Transfer Bank', 'Tunai', 'QRIS', 'E-Wallet', 'Kartu Debit/Kredit')),
  tanggal date not null,
  catatan text not null default '',
  status text not null default 'Menunggu' check (status in ('Menunggu', 'Diterima', 'Ditolak')),
  transaksi_id bigint references public.transaksi_bayar(id) on delete set null,
  diproses_oleh uuid references public.profiles(id) on delete set null,
  diproses_pada timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists laporan_bayar_status_idx on public.laporan_bayar (status, created_at);
-- Pembeli boleh lapor bayar SEBELUM invoice dibuat (paket katalog, harga sudah pasti).
-- Invoice dibuat otomatis saat owner/admin memverifikasi laporan pertama.
alter table public.laporan_bayar alter column pembayaran_id drop not null;
create index if not exists laporan_bayar_masuk_idx on public.laporan_bayar (pesanan_masuk_id);

-- Cari pesanan dari kode + nomor HP (dipakai dua fungsi di bawah)
create or replace function public.cari_pesanan_pembeli(p_kode text, p_hp text)
returns public.pesanan_masuk language plpgsql stable security definer set search_path = public as $$
declare r public.pesanan_masuk;
begin
  select * into r from public.pesanan_masuk
  where upper(kode) = upper(btrim(coalesce(p_kode, '')))
    and public.normalisasi_hp(no_hp) = public.normalisasi_hp(p_hp)
  limit 1;
  if r.id is null then raise exception 'Kode pesanan atau nomor HP tidak cocok.'; end if;
  return r;
end $$;
revoke execute on function public.cari_pesanan_pembeli(text, text) from public, anon, authenticated;

-- Ringkasan tagihan untuk satu pesanan online.
-- Sebelum invoice ada (paket katalog), tagihan dihitung dari tabel paket_harga
-- supaya pembeli bisa langsung bayar tanpa menunggu admin.
create or replace function public.cek_tagihan(p_kode text, p_hp text)
returns json language plpgsql stable security definer set search_path = public as $$
declare
  r public.pesanan_masuk;
  v_inv record;
  v_pk public.paket_harga;
  v_total numeric;
  v_hasil jsonb;
  v_laporan jsonb;
begin
  r := public.cari_pesanan_pembeli(p_kode, p_hp);
  v_laporan := coalesce((select jsonb_agg(jsonb_build_object('tanggal', l.tanggal, 'jumlah', l.jumlah, 'metode', l.metode, 'status', l.status) order by l.created_at desc)
                          from public.laporan_bayar l where l.pesanan_masuk_id = r.id), '[]'::jsonb);
  v_hasil := jsonb_build_object(
    'kode', r.kode, 'nama', r.nama, 'nama_event', r.nama_event, 'tanggal_event', r.tanggal_event,
    'jenis_paket', r.jenis_paket, 'jumlah_pax', r.jumlah_pax, 'status', r.status,
    'metode_bayar', r.metode_bayar, 'skema_bayar', r.skema_bayar, 'tempo_hari', r.tempo_hari,
    'dikirim', r.created_at, 'invoice', null, 'tagihan_awal', null);

  if r.pesanan_id is not null then
    select pe.no_pesanan, b.id, b.no_invoice, b.tanggal_tagihan, b.tanggal_tempo, b.total_tagihan,
           b.jumlah_dibayar, b.status_bayar, pe.metode_pembayaran, pe.harga_per_pax, pe.jumlah_pax,
           pe.total_penjualan, b.pajak_ppn, pe.jenis_paket
      into v_inv
      from public.pesanan_event pe join public.pembayaran b on b.pesanan_id = pe.id
      where pe.id = r.pesanan_id limit 1;
    if v_inv.id is not null then
      v_hasil := v_hasil || jsonb_build_object('invoice', jsonb_build_object(
        'no_pesanan', v_inv.no_pesanan, 'no_invoice', v_inv.no_invoice,
        'tanggal_tagihan', v_inv.tanggal_tagihan, 'tanggal_tempo', v_inv.tanggal_tempo,
        'total', v_inv.total_tagihan, 'dibayar', v_inv.jumlah_dibayar,
        'sisa', greatest(v_inv.total_tagihan - v_inv.jumlah_dibayar, 0),
        'status_bayar', v_inv.status_bayar, 'metode', v_inv.metode_pembayaran,
        -- rincian untuk invoice yang bisa dilihat pembeli
        'harga_per_pax', v_inv.harga_per_pax, 'jumlah_pax', v_inv.jumlah_pax, 'jenis_paket', v_inv.jenis_paket,
        'subtotal', v_inv.total_penjualan, 'pajak_ppn', v_inv.pajak_ppn,
        'riwayat', coalesce((select jsonb_agg(jsonb_build_object('tanggal', t.tanggal, 'jumlah', t.jumlah, 'metode', t.metode) order by t.tanggal, t.id)
                              from public.transaksi_bayar t where t.pembayaran_id = v_inv.id), '[]'::jsonb),
        'laporan', v_laporan
      ));
    end if;
  elsif r.status = 'Baru' then
    v_pk := public.harga_paket(r.jenis_paket);
    if v_pk.nama is not null then
      v_total := round(r.jumlah_pax * v_pk.harga, 2) + round(r.jumlah_pax * v_pk.harga * 0.11, 2);
      v_hasil := v_hasil || jsonb_build_object('tagihan_awal', jsonb_build_object(
        'total', v_total, 'dibayar', 0, 'sisa', v_total,
        'tanggal_tempo', r.tanggal_event + r.tempo_hari, 'metode', r.metode_bayar,
        'status_bayar', 'Belum Bayar', 'riwayat', '[]'::jsonb, 'laporan', v_laporan));
    end if;
  end if;
  return v_hasil::json;
end $$;

-- Pembeli lapor "Saya sudah bayar". Boleh sebelum invoice dibuat (paket katalog).
create or replace function public.lapor_bayar(
  p_kode text, p_hp text, p_jumlah numeric, p_metode text, p_tanggal date, p_catatan text default ''
) returns json language plpgsql security definer set search_path = public as $$
declare
  r public.pesanan_masuk;
  v_pembayaran bigint;
  v_total numeric;
  v_dibayar numeric := 0;
  v_menunggu numeric;
  v_sisa numeric;
  v_pk public.paket_harga;
begin
  r := public.cari_pesanan_pembeli(p_kode, p_hp);
  if r.status = 'Ditolak' then raise exception 'Pesanan ini tidak dapat dilayani, jadi tidak perlu dibayar.'; end if;

  if r.pesanan_id is not null then
    select b.id, b.total_tagihan, b.jumlah_dibayar into v_pembayaran, v_total, v_dibayar
      from public.pembayaran b where b.pesanan_id = r.pesanan_id limit 1;
  else
    v_pk := public.harga_paket(r.jenis_paket);
    if v_pk.nama is null then raise exception 'Harga paket custom belum dikonfirmasi admin. Tunggu kabar dari kami dulu, ya.'; end if;
    v_total := round(r.jumlah_pax * v_pk.harga, 2) + round(r.jumlah_pax * v_pk.harga * 0.11, 2);
  end if;
  if v_total is null then raise exception 'Tagihan belum tersedia.'; end if;

  select coalesce(sum(jumlah), 0) into v_menunggu from public.laporan_bayar
    where pesanan_masuk_id = r.id and status = 'Menunggu';
  v_sisa := v_total - v_dibayar - v_menunggu;

  if v_total - v_dibayar <= 0 then raise exception 'Tagihan ini sudah lunas.'; end if;
  if (select count(*) from public.laporan_bayar where pesanan_masuk_id = r.id and status = 'Menunggu') >= 3 then
    raise exception 'Masih ada 3 laporan yang menunggu verifikasi. Tunggu admin memeriksanya dulu.';
  end if;
  if p_jumlah is null or p_jumlah <= 0 then raise exception 'Isi jumlah yang dibayar.'; end if;
  -- Pembayaran pertama minimal DP 50% dari total (ubah angka 0.5 di sini dan dpMinimalPersen di pengaturan.js bersamaan)
  if v_dibayar = 0 and v_menunggu = 0 and p_jumlah < round(v_total * 0.5) - 0.5 then
    raise exception 'Pembayaran pertama minimal DP 50%% (Rp %).', replace(to_char(round(v_total * 0.5), 'FM999,999,999,990'), ',', '.');
  end if;
  if p_jumlah > v_sisa + 0.5 then
    raise exception 'Jumlah melebihi sisa tagihan (sisa Rp %).', replace(to_char(greatest(v_sisa, 0), 'FM999,999,999,990'), ',', '.');
  end if;
  if p_metode is null or p_metode not in ('Transfer Bank', 'Tunai', 'QRIS', 'E-Wallet', 'Kartu Debit/Kredit') then
    raise exception 'Pilih metode pembayaran.'; end if;
  if p_tanggal is null or p_tanggal > current_date or p_tanggal < current_date - 60 then
    raise exception 'Tanggal bayar tidak valid.'; end if;
  if length(coalesce(p_catatan, '')) > 300 then raise exception 'Catatan terlalu panjang (maks. 300 huruf).'; end if;

  insert into public.laporan_bayar (pesanan_masuk_id, pembayaran_id, jumlah, metode, tanggal, catatan)
  values (r.id, v_pembayaran, round(p_jumlah, 2), p_metode, p_tanggal, btrim(coalesce(p_catatan, '')));
  return json_build_object('ok', true);
end $$;

-- Owner/admin: VERIFIKASI 1 KLIK.
-- Jika pesanan online belum diterima, klik ini sekaligus: menerima pesanan,
-- membuat booking + invoice, lalu mencatat pembayarannya. Status invoice berubah otomatis.
create or replace function public.verifikasi_bayar(p_id bigint)
returns json language plpgsql security definer set search_path = public as $$
declare
  l public.laporan_bayar;
  m public.pesanan_masuk;
  v_harga numeric;
  v_pembayaran bigint;
  v_transaksi bigint;
  v_baru boolean := false;
begin
  if public.peran_saya() not in ('owner', 'admin') then
    raise exception 'Akun viewer tidak boleh memverifikasi pembayaran.';
  end if;
  select * into l from public.laporan_bayar where id = p_id for update;
  if l.id is null then raise exception 'Laporan pembayaran tidak ditemukan.'; end if;
  if l.status <> 'Menunggu' then raise exception 'Laporan ini sudah diproses (%).', l.status; end if;
  select * into m from public.pesanan_masuk where id = l.pesanan_masuk_id for update;
  if m.status = 'Ditolak' then raise exception 'Pesanan % sudah ditolak. Tolak juga laporan bayar ini.', m.kode; end if;

  v_pembayaran := l.pembayaran_id;
  if v_pembayaran is null then
    if m.pesanan_id is null then
      v_harga := (public.harga_paket(m.jenis_paket)).harga;
      if v_harga is null then raise exception 'Paket custom: isi harga & terima pesanan % dulu di menu Pesanan online.', m.kode; end if;
      perform public._booking_dari_online(m.id, v_harga);
      select pesanan_id into m.pesanan_id from public.pesanan_masuk where id = m.id;
      v_baru := true;
    end if;
    select b.id into v_pembayaran from public.pembayaran b where b.pesanan_id = m.pesanan_id limit 1;
    if v_pembayaran is null then raise exception 'Invoice untuk pesanan % tidak ditemukan.', m.kode; end if;
    update public.laporan_bayar set pembayaran_id = v_pembayaran where id = l.id;
  end if;

  insert into public.transaksi_bayar (pembayaran_id, tanggal, jumlah, metode, catatan)
  values (v_pembayaran, l.tanggal, l.jumlah, l.metode,
          'Dilaporkan pembeli (' || coalesce(m.kode, '-') || ')' || case when l.catatan <> '' then ': ' || l.catatan else '' end)
  returning id into v_transaksi;

  update public.laporan_bayar
    set status = 'Diterima', transaksi_id = v_transaksi, diproses_oleh = auth.uid(), diproses_pada = now()
    where id = p_id;
  return json_build_object('ok', true, 'pesanan_diterima', v_baru);
end $$;

-- Owner/admin: TOLAK pesanan online. Laporan bayar yang masih menunggu ikut ditolak.
create or replace function public.tolak_pesanan(p_id bigint)
returns json language plpgsql security definer set search_path = public as $$
begin
  if public.peran_saya() not in ('owner', 'admin') then raise exception 'Akun viewer tidak boleh menolak pesanan.'; end if;
  update public.pesanan_masuk set status = 'Ditolak', diproses_oleh = auth.uid(), diproses_pada = now()
    where id = p_id and status = 'Baru';
  if not found then raise exception 'Pesanan sudah diproses atau tidak ditemukan.'; end if;
  update public.laporan_bayar set status = 'Ditolak', diproses_oleh = auth.uid(), diproses_pada = now()
    where pesanan_masuk_id = p_id and status = 'Menunggu';
  return json_build_object('ok', true);
end $$;
