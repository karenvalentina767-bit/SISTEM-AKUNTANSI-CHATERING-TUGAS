  check (metode_pembayaran in ('Transfer Bank', 'Tunai', 'QRIS', 'E-Wallet', 'Kartu Debit/Kredit'));

-- Penomoran urut per tahun tanpa loncat: ORD-2026-0001, ORD-2026-0002, ...
create table if not exists public.penomoran (
  jenis text not null,
  tahun int not null,
  terakhir int not null default 0,
  primary key (jenis, tahun)
);

create or replace function public.nomor_berikut(p_jenis text, p_tahun int)
returns int language plpgsql security definer set search_path = public as $$
declare hasil int;
begin
  insert into public.penomoran (jenis, tahun, terakhir) values (p_jenis, p_tahun, 1)
  on conflict (jenis, tahun) do update set terakhir = public.penomoran.terakhir + 1
  returning terakhir into hasil;
  return hasil;
end $$;

create or replace function public.set_no_pesanan()
returns trigger language plpgsql security definer set search_path = public as $$
declare th int := extract(year from coalesce(new.created_at, now()))::int;
begin
  if new.no_pesanan is null then
    new.no_pesanan := 'ORD-' || th || '-' || lpad(public.nomor_berikut('ORD', th)::text, 4, '0');
  end if;
  return new;
end $$;
drop trigger if exists pesanan_no_trg on public.pesanan_event;
create trigger pesanan_no_trg before insert on public.pesanan_event
  for each row execute function public.set_no_pesanan();

-- Beri nomor urut ke pesanan lama (urut tanggal dibuat)
do $$
declare r record;
begin
  for r in select id, created_at from public.pesanan_event where no_pesanan is null order by created_at, id loop
    update public.pesanan_event
      set no_pesanan = 'ORD-' || extract(year from r.created_at)::int || '-' ||
        lpad(public.nomor_berikut('ORD', extract(year from r.created_at)::int)::text, 4, '0')
      where id = r.id;
  end loop;
end $$;
create unique index if not exists pesanan_no_idx on public.pesanan_event (no_pesanan);
create index if not exists pesanan_event_tanggal_idx on public.pesanan_event (tanggal_event);
create index if not exists pesanan_pelanggan_idx on public.pesanan_event (pelanggan_id);

