-- Dipanggil dari halaman pembeli. Memeriksa isian dan membatasi spam.
create or replace function public.kirim_pesanan(
  p_nama text, p_hp text, p_email text,
  p_nama_event text, p_tanggal_event date, p_paket text,
  p_pax int, p_catatan text default '',
  p_metode text default 'Transfer Bank', p_skema text default 'DP', p_tempo int default 7
) returns json language plpgsql security definer set search_path = public as $$
declare
  v_nama text := btrim(coalesce(p_nama, ''));
  v_hp text := btrim(coalesce(p_hp, ''));
  v_hp_normal text := public.normalisasi_hp(p_hp);
  v_email text := btrim(coalesce(p_email, ''));
  v_event text := btrim(coalesce(p_nama_event, ''));
  v_paket text := btrim(coalesce(p_paket, ''));
  v_catatan text := btrim(coalesce(p_catatan, ''));
  v_id bigint;
  v_kode text;
  v_paket_db public.paket_harga;
  v_total numeric;
begin
  if length(v_nama) < 2 or length(v_nama) > 100 then raise exception 'Nama wajib diisi (2–100 huruf).'; end if;
  if length(v_hp_normal) < 10 or length(v_hp_normal) > 15 or length(v_hp) > 25 then raise exception 'Nomor HP tidak valid.'; end if;
  if length(v_email) > 120 or (v_email <> '' and v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$') then raise exception 'Format email tidak valid.'; end if;
  if length(v_event) < 3 or length(v_event) > 150 then raise exception 'Nama acara wajib diisi (3–150 huruf).'; end if;
  if p_tanggal_event is null or p_tanggal_event < current_date + 1 then raise exception 'Tanggal acara paling cepat besok.'; end if;
  if p_tanggal_event > current_date + 730 then raise exception 'Tanggal acara maksimal 2 tahun dari sekarang.'; end if;
  if length(v_paket) < 2 or length(v_paket) > 100 then raise exception 'Pilih paket terlebih dahulu.'; end if;
  if p_pax is null or p_pax < 1 or p_pax > 10000 then raise exception 'Jumlah porsi tidak valid.'; end if;
  v_paket_db := public.harga_paket(v_paket);
  if v_paket_db.nama is not null and p_pax < v_paket_db.min_pax then
    raise exception 'Minimal % pax untuk paket %.', v_paket_db.min_pax, v_paket_db.nama; end if;
  if length(v_catatan) > 1000 then raise exception 'Catatan terlalu panjang (maks. 1000 huruf).'; end if;
  if p_metode is null or p_metode not in ('Transfer Bank', 'QRIS', 'E-Wallet', 'Kartu Debit/Kredit') then
    raise exception 'Pilih metode pembayaran (Transfer Bank, QRIS, E-Wallet, atau Kartu). Pembayaran tunai tidak tersedia.'; end if;
  -- ATURAN BAYAR: wajib DP dulu, atau langsung lunas. WAJIB LUNAS paling lambat H-1 (sehari sebelum acara).
  if p_skema is null or p_skema not in ('DP', 'Lunas') then raise exception 'Pilih cara bayar: DP dulu atau langsung lunas.'; end if;

  -- ATURAN TERLAMBAT
  -- 1) Masih punya tagihan yang lewat jatuh tempo → tidak bisa pesan lagi sebelum melunasi.
  if exists (
    select 1 from public.pelanggan pl
      join public.pesanan_event pe on pe.pelanggan_id = pl.id
      join public.pembayaran b on b.pesanan_id = pe.id
    where pl.no_hp_normal = v_hp_normal and b.status_bayar <> 'Lunas' and b.tanggal_tempo < current_date
  ) then
    raise exception 'Nomor ini masih punya tagihan yang lewat jatuh tempo. Lunasi dulu lewat menu Cek tagihan, lalu pesan lagi.';
  end if;
  -- 2) Pernah terlambat melunasi → pesanan berikutnya wajib bayar lunas di awal.
  if p_skema <> 'Lunas' and exists (
    select 1 from public.pelanggan pl
      join public.pesanan_event pe on pe.pelanggan_id = pl.id
      join public.pembayaran b on b.pesanan_id = pe.id
    where pl.no_hp_normal = v_hp_normal and b.status_bayar = 'Lunas'
      and (select max(t.tanggal) from public.transaksi_bayar t where t.pembayaran_id = b.id) > b.tanggal_tempo
  ) then
    raise exception 'Karena pembayaran sebelumnya pernah terlambat, pesanan ini wajib bayar lunas di awal. Pilih "Bayar lunas".';
  end if;

  -- Anti-spam: maks. 3 pesanan per nomor per 24 jam, dan 60 pesanan per jam untuk semua pembeli
  if (select count(*) from public.pesanan_masuk
      where public.normalisasi_hp(no_hp) = v_hp_normal and created_at > now() - interval '24 hours') >= 3 then
    raise exception 'Nomor ini sudah mengirim 3 pesanan hari ini. Silakan hubungi kami lewat telepon.';
  end if;
  if (select count(*) from public.pesanan_masuk where created_at > now() - interval '1 hour') >= 60 then
    raise exception 'Sedang banyak pesanan masuk. Coba lagi beberapa saat.';
  end if;

  insert into public.pesanan_masuk (nama, no_hp, email, nama_event, tanggal_event, jenis_paket, jumlah_pax, catatan,
    metode_bayar, skema_bayar, tempo_hari)
  values (v_nama, v_hp, v_email, v_event, p_tanggal_event, v_paket, p_pax, v_catatan, p_metode, p_skema, -1)  -- H-1 (samakan dengan hariLunasSebelumAcara)
  returning id into v_id;

  v_kode := 'WEB-' || lpad(v_id::text, 4, '0');
  update public.pesanan_masuk set kode = v_kode where id = v_id;
  -- Paket katalog: total sudah pasti, pembeli bisa langsung bayar. Paket custom: null (harga dari admin).
  if v_paket_db.nama is not null then
    v_total := round(p_pax * v_paket_db.harga, 2) + round(p_pax * v_paket_db.harga * 0.11, 2);
  end if;
  return json_build_object('kode', v_kode, 'total', v_total, 'tanggal_tempo', p_tanggal_event - 1);
end $$;

-- INTI: ubah pesanan online menjadi booking + invoice (tanpa cek peran).
-- Hanya dipanggil fungsi lain di bawah (terima_cepat, verifikasi_bayar), tidak bisa dipanggil dari browser.
create or replace function public._booking_dari_online(p_masuk_id bigint, p_harga numeric)
returns json language plpgsql security definer set search_path = public as $$
declare
  m public.pesanan_masuk;
  v_pelanggan bigint;
  v_baru boolean := false;
  v_pesanan record;
  v_subtotal numeric;
  v_ppn numeric;
  v_no_invoice text;
begin
  select * into m from public.pesanan_masuk where id = p_masuk_id for update;
  if m.id is null then raise exception 'Pesanan online tidak ditemukan.'; end if;
  if m.status <> 'Baru' then raise exception 'Pesanan online ini sudah diproses (%).', m.status; end if;
  if p_harga is null or p_harga <= 0 then raise exception 'Isi harga per pax.'; end if;
  v_subtotal := round(m.jumlah_pax * p_harga, 2);
  v_ppn := round(m.jumlah_pax * p_harga * 0.11, 2);

  select id into v_pelanggan from public.pelanggan
  where no_hp_normal = public.normalisasi_hp(m.no_hp) order by created_at limit 1;
  if v_pelanggan is null then
    insert into public.pelanggan (nama_pelanggan, no_hp, email)
    values (m.nama, m.no_hp, m.email) returning id into v_pelanggan;
    v_baru := true;
  elsif m.email <> '' then
    update public.pelanggan set email = m.email where id = v_pelanggan and email = '';
  end if;

  insert into public.pesanan_event (pelanggan_id, nama_event, tanggal_event, jenis_paket,
    jumlah_pax, harga_per_pax, total_penjualan, metode_pembayaran)
  values (v_pelanggan, m.nama_event, m.tanggal_event, m.jenis_paket, m.jumlah_pax, p_harga, v_subtotal, m.metode_bayar)
  returning id, no_pesanan into v_pesanan;

  v_no_invoice := replace(v_pesanan.no_pesanan, 'ORD-', 'INV-');
  insert into public.pembayaran (pesanan_id, no_invoice, tanggal_tagihan, tanggal_tempo, pajak_ppn, total_tagihan)
  values (v_pesanan.id, v_no_invoice, current_date, m.tanggal_event + m.tempo_hari, v_ppn, v_subtotal + v_ppn);

  update public.pesanan_masuk
    set status = 'Diterima', pesanan_id = v_pesanan.id, diproses_oleh = auth.uid(), diproses_pada = now()
    where id = m.id;
  return json_build_object('no_pesanan', v_pesanan.no_pesanan, 'no_invoice', v_no_invoice, 'pelanggan_baru', v_baru);
end $$;
revoke execute on function public._booking_dari_online(bigint, numeric) from public, anon, authenticated;

